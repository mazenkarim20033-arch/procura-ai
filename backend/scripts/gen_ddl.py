"""Write migrations/sql/schema_snapshot.sql: the full CURRENT schema generated from the models.

Run from backend/:  .venv/Scripts/python scripts/gen_ddl.py
This is informational and drift-checked (a test fails when it is stale). Migrations themselves are
frozen, hand-written files: 0001_initial.sql was generated once from the models, later changes live in
numbered files (0002_*.sql ...) executed by Alembic. An integration test compares the live database
schema with the models.
"""
from pathlib import Path

from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

from app.db.models import Base

ROOT = Path(__file__).resolve().parents[1]
SQL_DIR = ROOT / "migrations" / "sql"


def build() -> str:
    dialect = postgresql.dialect()
    parts = ["-- SNAPSHOT of the current schema, generated by scripts/gen_ddl.py. Not executed by migrations.\n",
             "create extension if not exists vector with schema extensions;\n"]
    for table in Base.metadata.sorted_tables:
        parts.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ";\n")
        for index in sorted(table.indexes, key=lambda i: i.name):
            parts.append(str(CreateIndex(index).compile(dialect=dialect)).strip() + ";\n")
    # Supabase exposes the public schema over PostgREST; with RLS on and no policies the
    # anon/authenticated roles see nothing. The backend connects as a privileged role.
    for table in Base.metadata.sorted_tables:
        parts.append(f"alter table public.{table.name} enable row level security;\n")
    parts.append((SQL_DIR / "0001_triggers.sql").read_text(encoding="utf-8"))
    return "\n".join(parts)


if __name__ == "__main__":
    out = SQL_DIR / "schema_snapshot.sql"
    out.write_text(build(), encoding="utf-8")
    print(f"wrote {out} ({out.stat().st_size} bytes)")
